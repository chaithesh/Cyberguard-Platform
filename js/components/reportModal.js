/**
 * SOC Security Incident Report Generator & Modal Handler
 */

let lastScanData = null;

export function setLastScanData(data) {
  lastScanData = data;
}

export function openReportModal() {
  const modal = document.getElementById('reportModal');
  const modalBody = document.getElementById('reportModalBody');
  if (!modal || !modalBody) return;

  const timestamp = new Date().toISOString();
  const reportId = 'INC-' + Math.floor(100000 + Math.random() * 900000);

  const reportContent = lastScanData ? lastScanData : {
    type: 'SYSTEM_AUDIT',
    summary: 'System Heuristic Phishing Engine Standing Audit',
    activeRules: 48,
    status: 'OPTIMAL'
  };

  modalBody.innerHTML = `
    <div style="font-family: var(--font-mono); font-size: 0.82rem; color: #fff;">
      <div style="display: flex; justify-content: space-between; border-bottom: 1px solid var(--border-glass); padding-bottom: 12px; margin-bottom: 16px;">
        <div>
          <span style="color: var(--text-muted)">REPORT ID:</span> <strong style="color: var(--cyan)">${reportId}</strong>
        </div>
        <div>
          <span style="color: var(--text-muted)">GENERATED:</span> <span>${timestamp}</span>
        </div>
      </div>

      <div style="background: rgba(0,0,0,0.4); border-radius: 8px; padding: 14px; margin-bottom: 16px; border: 1px solid rgba(255,255,255,0.08);">
        <h4 style="color: var(--cyan); margin-bottom: 6px;">INCIDENT SUMMARY & SCOPE</h4>
        <p style="color: var(--text-secondary);">
          Automated heuristic security audit generated by CyberGuard Threat Intelligence Platform.
        </p>
      </div>

      <h4 style="color: var(--cyan); margin-bottom: 8px;">RAW TELEMETRY PAYLOAD (JSON)</h4>
      <pre class="code-block" style="max-height: 240px;">${JSON.stringify(reportContent, null, 2)}</pre>
    </div>
  `;

  modal.classList.remove('hidden');

  // Setup Download & Print Event Handlers
  document.getElementById('downloadJsonReport').onclick = () => {
    const dataStr = "data:text/json;charset=utf-8," + encodeURIComponent(JSON.stringify(reportContent, null, 2));
    const dlAnchor = document.createElement('a');
    dlAnchor.setAttribute("href", dataStr);
    dlAnchor.setAttribute("download", `${reportId}_CyberGuard_SOC_Report.json`);
    document.body.appendChild(dlAnchor);
    dlAnchor.click();
    dlAnchor.remove();
  };

  document.getElementById('printReport').onclick = () => {
    window.print();
  };

  document.getElementById('closeReportModal').onclick = () => {
    modal.classList.add('hidden');
  };
}
